<?php
require_once __DIR__ . '/includes/community-auth.php';
require_once __DIR__ . '/includes/functions.php';
require_once __DIR__ . '/models/CommunitySavings.php';
require_once __DIR__ . '/models/CommunityLoan.php';
require_once __DIR__ . '/models/CommunityCustomer.php';

$customer_id = $_SESSION['community_customer_id'];
$savingsModel = new CommunitySavings($pdo);
$loanModel = new CommunityLoan($pdo);
$customerModel = new CommunityCustomer($pdo);
$customer = $customerModel->findById($customer_id);
$total_savings = $savingsModel->getBalance($customer_id);
$transactions = $savingsModel->getTransactions($customer_id);
$loans = $loanModel->getByCustomer($customer_id);

require_once __DIR__ . '/../dompdf/vendor/autoload.php';
use Dompdf\Dompdf;

$html = '<!DOCTYPE html><html><head><style>
body{font-family:Arial;font-size:12px;color:#333}
h1{color:#1a5928;border-bottom:3px solid #1a5928;padding-bottom:10px}
h2{color:#555;margin-top:20px;border-bottom:1px solid #ddd;padding-bottom:5px}
table{width:100%;border-collapse:collapse;margin:12px 0} th,td{padding:6px 8px;text-align:left;border-bottom:1px solid #eee;font-size:11px}
th{background:#f8f8f8;font-weight:bold} .text-right{text-align:right} .text-success{color:#198754} .text-danger{color:#dc3545}
.header-row{display:flex;justify-content:space-between} .summary-box{background:#f0fdf4;border:1px solid #bbf7d0;padding:15px;border-radius:8px;margin:15px 0}
</style></head><body>';
$html .= '<h1>Jera Moyie Community Statement</h1>';
$html .= '<table><tr><td><strong>' . htmlspecialchars($customer['full_name']) . '</strong><br>Phone: ' . htmlspecialchars($customer['phone_number']) . '<br>ID: ' . htmlspecialchars($customer['national_id']) . '</td>';
$html .= '<td class="text-right"><strong>Date:</strong> ' . date('d M Y, H:i') . '<br><strong>Account Since:</strong> ' . date('d M Y', strtotime($customer['created_at'])) . '</td></tr></table>';

$html .= '<div class="summary-box"><strong>Total Savings: KSh ' . number_format($total_savings, 2) . '</strong> &nbsp; | &nbsp; ';
$html .= '<strong>Total Loans:</strong> ' . count($loans) . '</div>';

$html .= '<h2>Savings Transactions</h2>';
if (empty($transactions)) {
    $html .= '<p style="color:#999">No transactions.</p>';
}
else {
    $html .= '<table><tr><th>Date</th><th>Product</th><th>Type</th><th class="text-right">Amount</th><th>Reference</th></tr>';
    foreach ($transactions as $t) {
        $sign = $t['transaction_type'] === 'deposit' ? '+' : '-';
        $color = $t['transaction_type'] === 'deposit' ? 'text-success' : 'text-danger';
        $html .= '<tr><td>' . date('d/m/Y', strtotime($t['created_at'])) . '</td><td>' . htmlspecialchars($t['product_name']) . '</td><td>' . ucfirst($t['transaction_type']) . '</td><td class="text-right ' . $color . '">' . $sign . 'KSh ' . number_format($t['amount'], 2) . '</td><td>' . $t['reference_code'] . '</td></tr>';
    }
    $html .= '</table>';
}

$html .= '<h2>Loan Summary</h2>';
if (empty($loans)) {
    $html .= '<p style="color:#999">No loans.</p>';
}
else {
    $html .= '<table><tr><th>Product</th><th class="text-right">Amount</th><th class="text-right">Repayable</th><th>Status</th><th>Due Date</th></tr>';
    foreach ($loans as $l) {
        $html .= '<tr><td>' . htmlspecialchars($l['product_name']) . '</td><td class="text-right">KSh ' . number_format($l['amount'], 2) . '</td><td class="text-right">KSh ' . number_format($l['total_repayable'], 2) . '</td><td>' . ucfirst($l['status']) . '</td><td>' . ($l['due_date'] ? date('d/m/Y', strtotime($l['due_date'])) : '—') . '</td></tr>';
    }
    $html .= '</table>';

    foreach ($loans as $l) {
        $repayments = $loanModel->getRepayments($l['id']);
        if (!empty($repayments)) {
            $html .= '<h2>Repayments — ' . htmlspecialchars($l['product_name']) . '</h2>';
            $html .= '<table><tr><th>Date</th><th class="text-right">Amount</th><th>Method</th><th>Reference</th></tr>';
            foreach ($repayments as $r) {
                $html .= '<tr><td>' . date('d/m/Y', strtotime($r['created_at'])) . '</td><td class="text-right">KSh ' . number_format($r['amount'], 2) . '</td><td>' . ucfirst($r['payment_method']) . '</td><td>' . $r['reference_code'] . '</td></tr>';
            }
            $html .= '</table>';
        }
    }
}

$html .= '<hr style="margin-top:30px"><p style="text-align:center;color:#999;font-size:10px">Generated by Jera Moyie Community Portal — ' . date('Y') . '</p></body></html>';

$dompdf = new Dompdf();
$dompdf->loadHtml($html);
$dompdf->setPaper('A4', 'portrait');
$dompdf->render();
$dompdf->stream('community_statement_' . date('Ymd') . '.pdf', ['Attachment' => true]);
